; ============================================================
; Next OS - Boot Code
;
; 역할:
;   1. GRUB이 넘겨준 32비트 환경에서 시작
;   2. 64비트 실행에 필요한 페이지 테이블 준비
;   3. CPU의 Long Mode(64비트 모드) 활성화
;   4. 64비트 코드로 점프
;   5. C++의 kernel_main() 실행
;
; CPU 흐름:
;
;   GRUB
;     ↓
;   32비트 Protected Mode
;     ↓
;   페이지 테이블 설정
;     ↓
;   PAE 활성화
;     ↓
;   Long Mode 활성화
;     ↓
;   Paging 활성화
;     ↓
;   64비트 코드로 점프
;     ↓
;   kernel_main()
;
; ============================================================


; ------------------------------------------------------------
; NASM에게 지금부터 나오는 코드를 32비트용으로 해석하라고 알림
;
; 주의:
; BITS 32는 CPU를 32비트로 "바꾸는" 명령이 아님.
; NASM이 명령어를 32비트 기준으로 만들어 주는 지시어임.
;
; 실제 CPU의 64비트 전환은 아래쪽에서 CR4 / EFER / CR0 /
; GDT / jmp를 이용해서 수행함.
; ------------------------------------------------------------

BITS 32


; ============================================================
; 1. Multiboot Header
; ============================================================
;
; GRUB에게:
; "이 커널은 Multiboot 형식을 사용한다."
; 라고 알려주는 정보.
;
; GRUB은 이 값을 보고 이 파일을 Multiboot 커널로 인식함.
; ============================================================


; Multiboot에서 요구하는 고정된 값
MULTIBOOT_MAGIC    equ 0x1BADB002

; Multiboot 옵션
; 현재는 특별한 옵션을 사용하지 않음
MULTIBOOT_FLAGS    equ 0

; 세 값을 더했을 때 0이 되도록 만드는 값
; GRUB이 헤더가 정상적인지 확인할 때 사용
MULTIBOOT_CHECKSUM equ -(MULTIBOOT_MAGIC + MULTIBOOT_FLAGS)


; Multiboot Header가 들어갈 섹션
section .multiboot

; 4바이트 경계에 맞춰 배치
align 4

; 실제 Multiboot Header 데이터
dd MULTIBOOT_MAGIC
dd MULTIBOOT_FLAGS
dd MULTIBOOT_CHECKSUM


; ============================================================
; 2. 외부에서 사용할 심볼
; ============================================================


; _start라는 이름을 다른 오브젝트 파일/링커에서도 볼 수 있게 공개
;
; 링커 스크립트에서:
;
;     ENTRY(_start)
;
; 로 이 위치를 프로그램 시작점으로 사용함.
global _start


; kernel_main은 C++ 파일에 존재함.
;
; 여기서는 구현하지 않고,
; "kernel_main이라는 함수가 다른 파일에 있다."
; 라고 NASM에게 알려주는 것.
extern kernel_main


; ============================================================
; 3. BSS
; ============================================================
;
; BSS:
; 초기값을 가지고 있지 않은 메모리 공간.
;
; 여기서는 실제 데이터 값을 저장하는 게 아니라
; 스택과 페이지 테이블에 사용할 공간만 예약함.
;
; .text → 실행할 코드
; .rodata → 읽기 전용 데이터
; .bss → 초기값이 없는 공간
; ============================================================


section .bss


; 페이지 테이블은 4096바이트 경계에 맞춰야 하므로
; 다음 공간을 4096바이트 경계에 맞춤.
align 4096


; ------------------------------------------------------------
; 4. Stack
; ------------------------------------------------------------

stack_bottom:

    ; 스택으로 사용할 공간 4096바이트 예약
    ;
    ; resb = Reserve Bytes
    ; 즉 "여기서부터 4096바이트를 비워둬라."
    resb 4096


; stack_top은 실제 데이터를 저장하는 공간이 아니라
; 방금 예약한 공간의 "끝 위치"를 가리키는 라벨.
;
; 스택은 일반적으로 높은 주소 → 낮은 주소 방향으로 사용하므로
; 처음에는 stack_top을 RSP에 넣어 사용함.
stack_top:


; ============================================================
; 5. 페이지 테이블 공간
; ============================================================
;
; 64비트 Long Mode에서 Paging을 사용하려면
; 페이지 테이블이 필요함.
;
; 우리가 사용할 구조:
;
;     PML4
;      ↓
;     PDPT
;      ↓
;      PD
;      ↓
;   실제 메모리
;
; 각각 4096바이트를 예약함.
; ============================================================


; 4096바이트 경계에 맞춤
align 4096

; PML4(Page Map Level 4)
; 최상위 페이지 테이블
pml4_table:

    ; 4096바이트 공간 예약
    resb 4096


; 다음 페이지 테이블도 4096바이트 경계에 맞춤
align 4096

; Page Directory Pointer Table
pdpt_table:

    ; 4096바이트 공간 예약
    resb 4096


; 다시 4096바이트 경계에 맞춤
align 4096

; Page Directory
pd_table:

    ; 4096바이트 공간 예약
    resb 4096


; ============================================================
; 6. 실제 실행 코드
; ============================================================


section .text


; ============================================================
; 7. 커널 시작점
; ============================================================
;
; GRUB이 커널을 메모리에 올린 뒤
; 가장 먼저 실행되는 곳.
; ============================================================


_start:


    ; 인터럽트를 잠시 비활성화
    ;
    ; CPU가 Long Mode 설정 중간에
    ; 다른 인터럽트를 처리하지 않도록 함.
    cli


    ; --------------------------------------------------------
    ; 8. 32비트 스택 설정
    ; --------------------------------------------------------
    ;
    ; 지금은 아직 32비트 상태이므로 ESP 사용.
    ;
    ; stack_top의 주소를 ESP에 넣음.
    ;
    ; 이후 push / call 등의 스택 동작에 사용할 수 있음.
    ; --------------------------------------------------------

    mov esp, stack_top


    ; ========================================================
    ; 9. PML4 → PDPT 연결
    ; ========================================================
    ;
    ; PML4의 첫 번째 항목이
    ; PDPT를 가리키도록 설정.
    ;
    ; 구조:
    ;
    ; PML4[0] → PDPT
    ;
    ; ========================================================


    ; PDPT의 주소를 EAX에 넣음
    mov eax, pdpt_table


    ; 페이지 테이블 항목의 플래그 설정
    ;
    ; 0x1 = Present
    ;      이 항목이 실제로 존재함
    ;
    ; 0x2 = Writable
    ;      쓰기 가능
    ;
    ; 0x3 = Present + Writable
    ;
    ; 주소의 낮은 비트는 이런 플래그로 사용됨.
    or eax, 0x3


    ; PML4의 첫 번째 항목에
    ; PDPT 주소 + 플래그를 저장
    mov [pml4_table], eax


    ; ========================================================
    ; 10. PDPT → PD 연결
    ; ========================================================
    ;
    ; 이번에는:
    ;
    ; PDPT[0] → PD
    ;
    ; 를 만듦.
    ; ========================================================


    ; PD의 주소를 EAX에 넣음
    mov eax, pd_table


    ; Present + Writable 플래그 추가
    or eax, 0x3


    ; PDPT의 첫 번째 항목에 저장
    mov [pdpt_table], eax


    ; ========================================================
    ; 11. PD에 2MiB 페이지 512개 만들기
    ; ========================================================
    ;
    ; PD의 각 항목 하나가 2MiB 영역을 가리키도록 설정함.
    ;
    ; 512 × 2MiB = 1GiB
    ;
    ; 따라서 처음 1GiB의 메모리를 연결할 수 있음.
    ; ========================================================


    ; PD 테이블의 시작 주소
    ; EDI는 현재 작성할 PD 항목의 위치를 가리키는 용도.
    mov edi, pd_table


    ; 첫 번째 페이지의 주소와 플래그
    ;
    ; 0x00000000 = 첫 번째 2MiB 영역의 시작 주소
    ;
    ; 0x80 = Page Size
    ;        2MiB 페이지를 사용한다는 뜻
    ;
    ; 0x03 = Present + Writable
    ;
    ; 따라서:
    ;
    ; 0x00000083
    ;
    ; = Present + Writable + 2MiB Page
    ;
    mov eax, 0x00000083


    ; 512개의 PD 항목을 만들 것이므로
    ; 반복 횟수를 ECX에 저장.
    mov ecx, 512


; 반복 시작 지점
.map_pd:


    ; 현재 페이지 정보를 PD에 기록
    ;
    ; EDI = 현재 PD 항목의 주소
    ; EAX = 현재 페이지의 주소 + 플래그
    mov [edi], eax


    ; 다음 2MiB 페이지로 이동
    ;
    ; 0x00200000 = 2MiB
    ;
    ; 예:
    ;
    ; 0x00000000
    ; 0x00200000
    ; 0x00400000
    ; 0x00600000
    ; ...
    ;
    add eax, 0x00200000


    ; PD의 다음 항목으로 이동
    ;
    ; PD 항목 하나는 64비트 = 8바이트
    ;
    ; 따라서 8바이트 이동.
    add edi, 8


    ; ECX를 1 감소시키고
    ; 아직 0이 아니면 .map_pd로 돌아감.
    loop .map_pd


    ; ========================================================
    ; 12. CR3에 PML4 주소 넣기
    ; ========================================================
    ;
    ; CR3는 현재 사용할 최상위 페이지 테이블의 주소를
    ; CPU에게 알려주는 레지스터.
    ;
    ; 여기서는:
    ;
    ; CR3 → PML4
    ;
    ; 로 설정함.
    ; ========================================================


    ; PML4 주소를 EAX에 넣음
    mov eax, pml4_table


    ; CR3에 PML4 주소 설정
    mov cr3, eax


    ; ========================================================
    ; 13. CR4의 PAE 비트 활성화
    ; ========================================================
    ;
    ; Long Mode의 Paging을 사용하려면
    ; PAE(Physical Address Extension)가 필요함.
    ;
    ; CR4의 bit 5가 PAE.
    ; ========================================================


    ; 현재 CR4 값을 EAX에 가져옴
    mov eax, cr4


    ; bit 5를 1로 설정
    ;
    ; 1 << 5
    ; = 0x20
    ;
    ; 즉 PAE 활성화.
    or eax, (1 << 5)


    ; 변경한 값을 CR4에 다시 저장
    mov cr4, eax


    ; ========================================================
    ; 14. EFER의 LME 활성화
    ; ========================================================
    ;
    ; EFER = Extended Feature Enable Register
    ;
    ; CPU의 MSR(Model Specific Register) 중 하나.
    ;
    ; EFER의 bit 8 = LME
    ; Long Mode Enable
    ;
    ; 이것을 1로 설정하면
    ; CPU가 Long Mode로 들어갈 준비를 함.
    ; ========================================================


    ; EFER MSR 번호
    ;
    ; 0xC0000080 = EFER
    ;
    ; ECX에 MSR 번호를 넣음.
    mov ecx, 0xC0000080


    ; EFER 값을 EDX:EAX로 읽음
    rdmsr


    ; EAX의 bit 8을 1로 설정
    ;
    ; LME = Long Mode Enable
    or eax, (1 << 8)


    ; 수정된 EFER 값을 다시 CPU에 기록
    wrmsr


    ; ========================================================
    ; 15. CR0의 Paging 활성화
    ; ========================================================
    ;
    ; CR0의 bit 31 = PG(Paging Enable)
    ;
    ; 지금까지:
    ;
    ; 페이지 테이블 준비
    ; PAE 활성화
    ; Long Mode Enable 활성화
    ;
    ; 를 했으므로 이제 Paging을 켬.
    ; ========================================================


    ; 현재 CR0 값을 EAX에 가져옴
    mov eax, cr0


    ; CR0의 bit 31을 1로 설정
    ;
    ; 1 << 31
    ; = Paging 활성화
    or eax, (1 << 31)


    ; 변경한 값을 CR0에 다시 저장
    mov cr0, eax


    ; ========================================================
    ; 16. GDT 로드
    ; ========================================================
    ;
    ; GDT = Global Descriptor Table
    ;
    ; CPU에게 코드 세그먼트와 데이터 세그먼트 정보를 알려줌.
    ;
    ; 아래에서 정의한 gdt_descriptor를 CPU에 등록.
    ; ========================================================


    ; GDT Descriptor를 GDTR에 로드
    lgdt [gdt_descriptor]


    ; ========================================================
    ; 17. 64비트 코드로 점프
    ; ========================================================
    ;
    ; 지금까지 Long Mode에 필요한 설정을 했지만
    ; CPU가 아직 기존 코드 세그먼트에서 실행 중임.
    ;
    ; Far Jump를 이용해서
    ; GDT의 0x08 코드 세그먼트로 이동.
    ;
    ; 0x08:
    ;   GDT의 두 번째 항목
    ;   = 64비트 코드 세그먼트
    ;
    ; long_mode_start:
    ;   실제 64비트 코드가 시작되는 위치
    ; ========================================================


    jmp 0x08:long_mode_start


; ============================================================
; 18. 여기서부터 64비트 코드
; ============================================================
;
; 이 지점에 도착하면 CPU는 Long Mode에서 실행 중.
;
; BITS 64는 NASM에게 이후 코드를 64비트 명령어로
; 어셈블하라고 알려주는 지시어.
; ============================================================


BITS 64


long_mode_start:


    ; ========================================================
    ; 19. 데이터 세그먼트 설정
    ; ========================================================
    ;
    ; 0x10 = GDT의 세 번째 항목
    ;       = 데이터 세그먼트
    ;
    ; DS = Data Segment
    ; ES = Extra Segment
    ; SS = Stack Segment
    ;
    ; 64비트 모드에서는 세그먼트 사용 방식이 크게
    ; 단순화되지만 초기 설정을 해둠.
    ; ========================================================


    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax


    ; ========================================================
    ; 20. 64비트 스택 설정
    ; ========================================================
    ;
    ; 이제 CPU가 64비트 모드이므로
    ; 64비트 Stack Pointer인 RSP를 사용.
    ;
    ; 네가 원래 가지고 있던 코드가 여기로 이동한 것.
    ; ========================================================


    mov rsp, stack_top


    ; ========================================================
    ; 21. C++ 커널 실행
    ; ========================================================
    ;
    ; 이제 드디어 C++의 kernel_main()을 실행.
    ;
    ; kernel.cpp:
    ;
    ; extern "C" void kernel_main()
    ;
    ; 과 연결됨.
    ; ========================================================


    call kernel_main


; ============================================================
; 22. kernel_main이 돌아왔을 때
; ============================================================
;
; 커널의 main 함수가 끝나더라도
; CPU가 이상한 메모리를 계속 실행하면 안 됨.
;
; 그래서 여기서 CPU를 멈춰놓음.
; ============================================================


.hang:

    ; 인터럽트 비활성화
    cli

    ; CPU를 정지
    hlt

    ; 혹시 다시 실행된다면 다시 정지
    jmp .hang


; ============================================================
; 23. 읽기 전용 데이터
; ============================================================


section .rodata


; ============================================================
; 24. GDT
; ============================================================
;
; GDT에는 세 개의 항목이 있음.
;
; GDT[0] = 0
; GDT[1] = 64비트 코드 세그먼트
; GDT[2] = 데이터 세그먼트
;
; 그래서:
;
; 0x00 → GDT[0]
; 0x08 → GDT[1]
; 0x10 → GDT[2]
;
; ============================================================


gdt:


    ; --------------------------------------------------------
    ; GDT[0]
    ;
    ; 첫 번째 항목은 반드시 비워둠.
    ; --------------------------------------------------------

    dq 0


    ; --------------------------------------------------------
    ; GDT[1]
    ;
    ; 64비트 코드 세그먼트.
    ;
    ; 위에서:
    ;
    ;     jmp 0x08:long_mode_start
    ;
    ; 할 때 이 항목을 사용함.
    ; --------------------------------------------------------

    dq 0x00209A0000000000


    ; --------------------------------------------------------
    ; GDT[2]
    ;
    ; 데이터 세그먼트.
    ;
    ; 위에서:
    ;
    ;     mov ax, 0x10
    ;
    ; 으로 DS / ES / SS에 넣음.
    ; --------------------------------------------------------

    dq 0x0000920000000000


; ============================================================
; 25. GDT Descriptor
; ============================================================
;
; LGDT 명령어가 읽는 정보.
;
; 구조:
;
;   dw = GDT 크기 - 1
;   dd = GDT 시작 주소
;
; ============================================================


gdt_descriptor:


    ; GDT 전체 크기 - 1
    ;
    ; $ = 현재 위치
    ; gdt = GDT 시작 위치
    ;
    ; 따라서:
    ;
    ; $ - gdt - 1
    ;
    ; = GDT의 마지막 바이트까지의 크기
    dw $ - gdt - 1


    ; GDT의 주소
    dd gdt
